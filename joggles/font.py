FALLBACK = ["###", "#.#", "#.#", "#.#", "###"]


def glyph(ch: str) -> list[list[int]]:
    """Return a [row][col] bitmap, bottom row first."""
    rows = _GLYPHS.get(ch.upper(), FALLBACK)
    return [[1 if p == "#" else 0 for p in line] for line in reversed(rows)]


def width(ch: str) -> int:
    return len(_GLYPHS.get(ch.upper(), FALLBACK)[0])


def text_bitmap(text: str, spacing: int = 1) -> list[list[int]]:
    """Render a whole string to a [row][col] bitmap, bottom row first."""
    total = sum(width(c) + spacing for c in text)
    total = max(total - spacing, 0)
    out = [[0] * total for _ in range(HEIGHT)]
    x = 0
    for ch in text:
        g = glyph(ch)
        w = width(ch)
        for r in range(HEIGHT):
            for c in range(w):
                if g[r][c]:
                    out[r][x + c] = 1
        x += w + spacing
    return out


def text_width(text: str, spacing: int = 1) -> int:
    total = sum(width(c) + spacing for c in text)
    return max(total - spacing, 0)
